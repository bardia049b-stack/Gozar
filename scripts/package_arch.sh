#!/bin/sh
set -eu

bundle=$1
output=$2
version=$3
root=$(CDPATH='' cd -- "$(dirname -- "$0")/.." && pwd)
case "$version" in *[!0-9.+~a-zA-Z-]*) echo "invalid version" >&2; exit 1;; esac

stage=$(mktemp -d)
trap 'rm -rf "$stage"' EXIT HUP INT TERM
mkdir -p "$stage/usr/lib/gozar" "$stage/usr/bin" "$stage/usr/share/applications" \
	"$stage/usr/share/pixmaps" "$stage/usr/share/licenses/gozar"

cp -a "$bundle/." "$stage/usr/lib/gozar/"
install -m 644 "$root/packaging/linux/gozar.desktop" "$stage/usr/share/applications/gozar.desktop"
install -m 644 "$root/desktop_flutter/assets/gozar.png" "$stage/usr/share/pixmaps/gozar.png"
for license in LICENSE NOTICE WINTUN-LICENSE.txt QUIC-GO-LICENSE.txt QPACK-LICENSE.txt GO-DEPS-LICENSES.txt; do
	install -m 644 "$root/$license" "$stage/usr/share/licenses/gozar/$license"
done
printf '#!/bin/sh\nexec /usr/lib/gozar/gozar "$@"\n' > "$stage/usr/bin/gozar"
chmod 755 "$stage/usr/bin/gozar"
chmod -R a+rX "$stage"

size=$(du -sb "$stage" | cut -f1)
builddate=$(date -u +%s)

cat > "$stage/.PKGINFO" <<PKGINFO
# Generated by Gozar packaging
pkgname = gozar
pkgbase = gozar
pkgver = $version-1
pkgdesc = Firefox Private Network client
url = https://github.com/bardia049b-stack/Gozar1
builddate = $builddate
packager = Gozar contributors <noreply@github.com>
size = $size
arch = x86_64
license = AGPL-3.0-or-later
depend = gtk3
depend = glib2
depend = cairo
depend = pango
depend = harfbuzz
depend = gdk-pixbuf2
depend = libstdc++
depend = zlib
depend = iproute2
PKGINFO

(
	cd "$stage"
	bsdtar -czf .MTREE --format=mtree \
		--options='!all,use-set,type,uid,gid,mode,time,size,md5,sha256,link' \
		.PKGINFO usr
	bsdtar -cf - .PKGINFO .MTREE usr | zstd -q -19 -T0 -o "$output"
)

ls -l "$output"
